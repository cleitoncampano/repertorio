import {test,expect} from '@playwright/test';

const evidence='/tmp/repertorio-graph-views-qa';
const switchTo=async(page:any,name:string)=>{
 await page.getByRole('button',{name:'Visualização do grafo',exact:true}).click();
 await page.getByRole('menuitemradio',{name,exact:true}).click();
};
const graph=async(page:any)=>page.evaluate(()=>{
 const c=(document.querySelector('.map-surface') as any)._cyreg.cy;
 return {ids:c.elements().map((element:any)=>element.id()).sort(),marker:c.scratch('qa-view'),positions:c.nodes().map((node:any)=>({id:node.id(),...node.position()})),zoom:c.zoom(),pan:c.pan(),images:c.nodes('[type="reference"]').map((node:any)=>node.data('image')),active:c.nodes('.active').map((node:any)=>node.id())};
});

test('troca a organização sem recriar o grafo ou perder seleção, busca e filtros',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/?workspace=pp-treta&ref=deck');
 await expect(page.locator('.detail-body h2')).toHaveText('Abertura criativa');
 await expect(page.locator('.map-stage')).toHaveAttribute('data-view','free');
 await expect.poll(async()=>(await graph(page)).images.some((image:string)=>image&&image!=='none')).toBe(true);
 await page.evaluate(()=>{(document.querySelector('.map-surface') as any)._cyreg.cy.scratch('qa-view','same-instance');});
 const original=await graph(page),bounds=await page.locator('.map-stage').boundingBox();
 await page.getByRole('button',{name:'Visualização do grafo',exact:true}).click();
 await page.screenshot({path:evidence+'/menu-desktop-escuro.png',animations:'disabled'});
 await page.keyboard.press('Escape');
 await expect(page.getByRole('menu',{name:'Visualização do grafo'})).toBeHidden();
 await expect(page.locator('.detail-body h2')).toHaveText('Abertura criativa');
 await expect(page.getByRole('button',{name:'Visualização do grafo',exact:true})).toBeFocused();
 await switchTo(page,'Por grupos');
 await expect(page.locator('.map-stage')).toHaveAttribute('data-view','grouped');
 const grouped=await graph(page);
 expect(grouped.ids).toEqual(original.ids);
 expect(grouped.marker).toBe('same-instance');
 expect(grouped.images.filter((image:string)=>image&&image!=='none').length).toBeGreaterThanOrEqual(original.images.filter((image:string)=>image&&image!=='none').length);
 expect(grouped.positions).not.toEqual(original.positions);
 expect(grouped.active).toEqual(['ref:deck']);
 await expect(page.locator('.detail-body h2')).toHaveText('Abertura criativa');
 expect(await page.locator('.map-stage').boundingBox()).toEqual(bounds);
 await page.getByRole('button',{name:'Fechar detalhes',exact:true}).click();
 await page.getByRole('textbox',{name:'Buscar inspiração'}).fill('Abertura');
 await page.getByRole('button',{name:'Explorar',exact:true}).click();
 await expect(page.locator('.result-row').filter({hasText:'Abertura criativa'})).toBeVisible();
 await switchTo(page,'Hierárquico');
 await expect(page.getByRole('textbox',{name:'Buscar inspiração'})).toHaveValue('Abertura');
 expect(new URL(page.url()).searchParams.get('q')).toBe('Abertura');
 await expect(page.locator('.result-row').filter({hasText:'Abertura criativa'})).toBeVisible();
 const hierarchy=await graph(page);
 expect(hierarchy.marker).toBe('same-instance');
 expect(hierarchy.positions).not.toEqual(grouped.positions);
 await page.screenshot({path:evidence+'/hierarquia-busca.png',animations:'disabled'});
 await page.getByRole('button',{name:'Limpar filtros',exact:true}).click();
 await page.getByRole('button',{name:'Diferenciação',exact:true}).click();
 await switchTo(page,'Por grupos');
 await expect(page.getByRole('complementary',{name:'Detalhes do eixo'})).toBeVisible();
 expect((await graph(page)).ids).toEqual(original.ids);
 expect(errors).toEqual([]);
});

test('lembra o modo e uma câmera independente por organização e permite escolher com teclado',async({page,request})=>{
 await page.goto('/?workspace=pp-treta');
 await expect(page.locator('canvas').first()).toBeVisible();
 const camera=async(zoom:number,x:number)=>page.evaluate(({zoom,x})=>{(document.querySelector('.map-surface') as any)._cyreg.cy.viewport({zoom,pan:{x,y:300}});},{zoom,x});
 await camera(.4,500);
 await page.getByRole('button',{name:'Visualização do grafo',exact:true}).focus();
 await page.keyboard.press('ArrowDown');
 await expect(page.getByRole('menuitemradio',{name:'Mapa livre',exact:true})).toBeFocused();
 await page.keyboard.press('ArrowDown');
 await page.keyboard.press('Enter');
 await expect(page.locator('.map-stage')).toHaveAttribute('data-view','grouped');
 await camera(.6,700);
 await switchTo(page,'Mapa livre');
 expect((await graph(page)).zoom).toBeCloseTo(.4);
 expect((await graph(page)).pan.x).toBeCloseTo(500);
 await switchTo(page,'Por grupos');
 expect((await graph(page)).zoom).toBeCloseTo(.6);
 expect((await graph(page)).pan.x).toBeCloseTo(700);
 await page.reload();
 await expect(page.locator('.map-stage')).toHaveAttribute('data-view','grouped');
 await expect(page.locator('canvas').first()).toBeVisible();
 expect((await graph(page)).zoom).toBeCloseTo(.6);
 expect((await graph(page)).pan.x).toBeCloseTo(700);
 const empty=await (await request.post('/api/workspaces',{data:{name:'Grafo vazio QA'}})).json();
 await page.goto('/?workspace='+empty.id);
 await expect(page.getByRole('heading',{name:'O repertório começa aqui.'})).toBeVisible();
 await page.getByRole('button',{name:'Visualização do grafo',exact:true}).click();
 await expect(page.getByRole('menuitemradio',{name:'Por grupos',exact:true})).toHaveAttribute('aria-checked','true');
 await page.keyboard.press('Escape');
 await page.goto('/?workspace=pp-treta');
 await expect(page.locator('canvas').first()).toBeVisible();
 expect((await graph(page)).pan.x).toBeCloseTo(700);
});

