 const menu=page.getByRole('menu',{name:'Visualização do grafo'}),rect=(await menu.boundingBox())!;
 expect(rect.x).toBeGreaterThanOrEqual(0);expect(rect.x+rect.width).toBeLessThanOrEqual(390);
 await page.screenshot({path:evidence+'/menu-mobile-claro.png',animations:'disabled'});
 await page.getByRole('menuitemradio',{name:'Hierárquico',exact:true}).click();
 await expect(page.locator('.map-stage')).toHaveAttribute('data-view','hierarchy');
 expect(await page.locator('.map-stage').boundingBox()).toEqual(bounds);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:evidence+'/hierarquia-mobile-claro.png',animations:'disabled'});
 await page.setViewportSize({width:320,height:740});
 const header=(await page.locator('.workspace-bar').boundingBox())!,toggle=(await page.getByRole('button',{name:'Visualização do grafo',exact:true}).boundingBox())!;
