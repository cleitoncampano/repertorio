import {test,expect} from '@playwright/test';

const evidence='/tmp/repertorio-skills-qa';

test('catálogo curado, busca por objetivo e pedido ligado ao espaço',async({page,context,request})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await context.grantPermissions(['clipboard-read','clipboard-write']);
 const space=await (await request.post('/api/workspaces',{data:{name:'GrowMate Skills QA'}})).json();
 await page.goto('/?workspace='+space.id);
 await page.getByRole('button',{name:'Skills',exact:true}).click();
 await expect(page.getByRole('button',{name:'Skills',exact:true})).toHaveAttribute('aria-current','page');
 await expect(page.getByRole('button',{name:'Entradas',exact:true})).toHaveCount(0);
 await expect(page.locator('.skill-card h2')).toHaveText(['Impeccable','Frontend Design','Landing Page Design','Detalhes que encantam','Design no estilo Apple','Protótipo em variações','Teste de limites','Cara de app no celular','Criar animação','Animação em app de celular','Revisão de animações','Plano de animações','Onde animar','Animação sem travar','Nome do efeito','ImageGen','Presentations','HyperFrames','HyperFrames Creative','Tese e roteiro','Aula e workshop','Revisão de apresentação','Escolher biblioteca','Avisos com Sonner','Swift moderno']);
 await expect(page.locator('.skills-context')).toContainText('GrowMate Skills QA');
 await page.screenshot({path:evidence+'/catalogo-escuro.png',animations:'disabled'});
 await page.locator('.skill-card').last().scrollIntoViewIfNeeded();
 await page.screenshot({path:evidence+'/catalogo-final-escuro.png',animations:'disabled'});
 await page.reload();
 await expect(page.getByRole('heading',{name:'O que vamos criar?'})).toBeVisible();
 await page.getByRole('group',{name:'Categorias de skills'}).getByRole('button',{name:'Design',exact:true}).click();
 await expect(page.locator('.skill-card')).toHaveCount(8);
 await page.getByRole('textbox',{name:'Buscar skills'}).fill('CONVERSOES');
 await expect(page.locator('.skill-card h2')).toHaveText(['Landing Page Design']);
 await page.getByRole('textbox',{name:'Buscar skills'}).fill('termo inexistente');
 await expect(page.getByRole('heading',{name:'Nenhuma skill encontrada.'})).toBeVisible();
 await page.getByRole('button',{name:'Ver todas as skills',exact:true}).click();
 await page.getByRole('button',{name:'Montar pedido com Frontend Design',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Frontend Design'});
 await dialog.getByRole('textbox',{name:'O que você quer criar ou melhorar?'}).fill('Crie um painel para líderes de CX.');
 const preview=dialog.getByRole('textbox',{name:'Seu pedido para o agente'});
 await expect(preview).toHaveValue(/skill frontend-design/);
 await expect(preview).toHaveValue(/Crie um painel para líderes de CX\./);
 await expect(preview).toHaveValue(/GrowMate Skills QA/);
 expect(await preview.inputValue()).toContain(space.id);
 await expect(preview).not.toHaveValue(/Referências/);
 await dialog.getByRole('button',{name:'Copiar pedido',exact:true}).click();
 await expect(dialog.getByRole('status')).toContainText('Pedido copiado');
 expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(await preview.inputValue());
 await page.screenshot({path:evidence+'/pedido-escuro.png',animations:'disabled'});
 await dialog.getByRole('textbox',{name:'O que você quer criar ou melhorar?'}).fill('   ');
 await expect(dialog.getByRole('button',{name:'Copiar pedido',exact:true})).toBeDisabled();
 await page.keyboard.press('Escape');
 await expect(dialog).toBeHidden();
 await expect(page.getByRole('button',{name:'Montar pedido com Frontend Design',exact:true})).toBeFocused();
 await page.getByRole('button',{name:'Espaços',exact:true}).click();
 await page.locator('.space-enter').filter({hasText:/^Referências/}).click();
 await expect(page.getByRole('heading',{name:'O que vamos criar?'})).toBeVisible();
 await page.getByRole('button',{name:'Montar pedido com Impeccable',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'Seu pedido para o agente'})).toHaveValue(/Referências/);
 await expect(page.getByRole('textbox',{name:'Seu pedido para o agente'})).not.toHaveValue(/GrowMate Skills QA/);
 expect(errors).toEqual([]);
});

test('skills globais, navegação e celular em tema claro sem transbordamento',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/?workspace=&view=skills');
 await expect(page.locator('.skill-card')).toHaveCount(25);
 await expect(page.locator('.spaces-home')).toHaveCount(0);
 await page.getByRole('button',{name:'Ativar modo claro',exact:true}).click();
 await expect(page.locator('.skills-context')).toContainText('Escolha um espaço');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.screenshot({path:evidence+'/catalogo-mobile-claro.png',animations:'disabled'});
 await page.getByRole('button',{name:'Montar pedido com Impeccable',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'Seu pedido para o agente'})).toHaveValue(/me pergunte qual espaço/);
 await page.screenshot({path:evidence+'/pedido-mobile-claro.png',animations:'disabled'});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Mapa',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Seu repertório, em espaços.'})).toBeVisible();
 await page.goBack();
 await expect(page.getByRole('heading',{name:'O que vamos criar?'})).toBeVisible();
});
